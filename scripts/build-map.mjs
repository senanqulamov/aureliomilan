// Generates lib/map-data.js — a cropped Europe→Caspian map as SVG paths
// plus the Mercator constants needed to place pins at runtime.
// Run: node scripts/build-map.mjs   (only needed if you change the crop)
import { readFileSync, writeFileSync } from 'node:fs';
import { feature, mesh } from 'topojson-client';
import { geoMercator, geoPath, geoBounds } from 'd3-geo';

const W = 1000;
const BBOX = { west: -11, east: 58, south: 33.5, north: 57 };
// Countries he has worked in get a warmer fill (ISO 3166 numeric ids)
const HIGHLIGHT = ['250', '380', '031'];

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'));
const all = feature(topo, topo.objects.countries);
// keep only countries that touch the crop (the SVG viewBox clips the rest)
const touches = (f) => { const [[w, s], [e, n]] = geoBounds(f); return !(e < BBOX.west - 2 || w > BBOX.east + 2 || n < BBOX.south - 2 || s > BBOX.north + 2) || e < w; };
const countries = { ...all, features: all.features.filter(touches) };

const rad = Math.PI / 180;
const merc = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * rad) / 2));
const scale = W / ((BBOX.east - BBOX.west) * rad);
const projection = geoMercator().scale(scale).translate([-scale * BBOX.west * rad, scale * merc(BBOX.north)]);
const H = Math.round(scale * (merc(BBOX.north) - merc(BBOX.south)));
projection.clipExtent([[0, 0], [W, H]]);

const path = geoPath(projection).digits(1);
const land = countries.features.filter((f) => !HIGHLIGHT.includes(String(f.id))).map((f) => path(f)).filter(Boolean).join('');
const hi = countries.features.filter((f) => HIGHLIGHT.includes(String(f.id))).map((f) => path(f)).filter(Boolean).join('');
const keep = new Set(countries.features.map((f) => f.id));
const borders = path(mesh(topo, topo.objects.countries, (a, b) => a !== b && (keep.has(a.id) || keep.has(b.id))));

const [tx, ty] = projection.translate();
writeFileSync('lib/map-data.js', `// Auto-generated by scripts/build-map.mjs
export const MAP = { w: ${W}, h: ${H}, scale: ${projection.scale().toFixed(4)}, tx: ${tx.toFixed(4)}, ty: ${ty.toFixed(4)} };
export const LAND = '${land}';
export const HIGHLIGHT_LAND = '${hi}';
export const BORDERS = '${borders}';
`);
console.log('map', W, 'x', H, 'bytes', (land.length + hi.length + borders.length));
