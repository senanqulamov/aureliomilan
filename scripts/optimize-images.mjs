// Converts originals/<folder>/*.jpg → public/photos/<name>-{800,1600}.webp
// and writes lib/photos.js (a manifest with literal paths + intrinsic sizes).
import sharp from 'sharp';
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const SRC = 'originals';
const OUT = 'public/photos';
const WIDTHS = [800, 1600];
mkdirSync(OUT, { recursive: true });

const manifest = {};
for (const folder of readdirSync(SRC)) {
  for (const file of readdirSync(join(SRC, folder)).filter(f => /\.jpe?g$/i.test(f))) {
    const name = basename(file).replace(/\.jpe?g$/i, '');
    const input = sharp(join(SRC, folder, file)).rotate();
    const meta = await input.metadata();
    const entry = { w: meta.width, h: meta.height };
    for (const w of WIDTHS) {
      const out = `${name}-${w}.webp`;
      await sharp(join(SRC, folder, file)).rotate()
        .resize({ width: Math.min(w, meta.width), withoutEnlargement: true })
        .webp({ quality: 78 }).toFile(join(OUT, out));
      entry[w === 800 ? 's' : 'l'] = `/photos/${out}`;
    }
    manifest[name] = entry;
    console.log('✓', name);
  }
}
const body = Object.entries(manifest)
  .map(([k, v]) => `  '${k}': { s: '${v.s}', l: '${v.l}', w: ${v.w}, h: ${v.h} },`)
  .join('\n');
writeFileSync('lib/photos.js', `// Generated by scripts/optimize-images.mjs\nexport const photos = {\n${body}\n};\n`);
